// Command generate_skill_recovery extracts skill release action durations
// from a local, already-extracted Shaiya client data directory. It emits only
// numeric timings; it does not copy client assets into the server package.
package main

import (
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"io"
	"math"
	"os"
	"path"
	"sort"
	"strings"

	"github.com/Spelunkern/Shaiya-GX/internal/data/archive"
	"github.com/Spelunkern/Shaiya-GX/internal/data/model"
	"github.com/Spelunkern/Shaiya-GX/internal/data/sdata"
)

type recoveryKey struct {
	id    uint16
	level uint8
}

func main() {
	clientData := flag.String("client-data", "", "path to the extracted client data directory")
	output := flag.String("out", "server/internal/world/skill_recovery_generated.go", "output Go file")
	appOutput := flag.String("app-out", "internal/app/skill_recovery_generated.go", "client output Go file")
	flag.Parse()
	if *clientData == "" {
		fatal("-client-data is required")
	}

	arc, err := archive.OpenDirectory(*clientData)
	if err != nil {
		fatal("open client data: %v", err)
	}
	assetHash := sha256.New()
	clips := map[string]float64{}
	actionDurations := map[int]float64{}
	var actionFiles []string
	arc.Walk(func(file string, _ *archive.File) {
		if strings.HasSuffix(strings.ToLower(file), "_action.alt") {
			actionFiles = append(actionFiles, file)
		}
	})
	sort.Strings(actionFiles)
	for _, file := range actionFiles {
		b, err := arc.ReadFile(file)
		if err != nil {
			fatal("read %s: %v", file, err)
		}
		_, _ = io.WriteString(assetHash, strings.ToLower(file)+"\x00")
		_, _ = assetHash.Write(b)
		actions, err := model.ParseALT(b)
		if err != nil {
			fatal("parse %s: %v", file, err)
		}
		folder := path.Dir(file)
		for slot, action := range actions {
			if action.Name == "" {
				continue
			}
			aniFile := path.Join(folder, "ANI", path.Base(action.Name))
			key := strings.ToLower(aniFile)
			duration, found := clips[key]
			if !found {
				aniBytes, err := arc.ReadFile(aniFile)
				if err != nil {
					continue
				}
				_, _ = io.WriteString(assetHash, key+"\x00")
				_, _ = assetHash.Write(aniBytes)
				ani, err := model.ParseANI(aniBytes)
				if err != nil {
					fatal("parse %s: %v", aniFile, err)
				}
				if ani.End < ani.Start {
					continue
				}
				duration = float64(ani.End-ani.Start) / 30
				clips[key] = duration
			}
			if duration > actionDurations[slot] {
				actionDurations[slot] = duration
			}
		}
	}
	if len(actionFiles) == 0 {
		fatal("no *_action.alt files found under %s", *clientData)
	}

	skillBytes, err := arc.ReadFile("Character/Skill.SData")
	if err != nil {
		fatal("read Character/Skill.SData: %v", err)
	}
	skillHash := sha256.Sum256(skillBytes)
	skills, err := sdata.ParseSkills(skillBytes)
	if err != nil {
		fatal("parse Character/Skill.SData: %v", err)
	}
	keys := make([]recoveryKey, 0, len(skills))
	durations := make(map[recoveryKey]uint32, len(skills))
	for key, skill := range skills {
		if key.Level == 0 {
			continue
		}
		maxDuration := 0.0
		for weapon := uint8(1); weapon <= 15; weapon++ {
			for variant := uint8(0); variant < 4; variant++ {
				slot := skillAction(skill.Animation, skill.Attack, skill.Effect, weapon, variant)
				if duration := actionDurations[slot]; duration > maxDuration {
					maxDuration = duration
				}
			}
		}
		if maxDuration <= 0 {
			continue
		}
		// Round up to the server's 100 ms world tick so a client cannot move
		// before the longest matching native action has fully elapsed.
		millis := uint32(math.Ceil(maxDuration*10) * 100)
		recoveryKey := recoveryKey{key.ID, key.Level}
		keys = append(keys, recoveryKey)
		durations[recoveryKey] = millis
	}
	sort.Slice(keys, func(i, j int) bool {
		if keys[i].id != keys[j].id {
			return keys[i].id < keys[j].id
		}
		return keys[i].level < keys[j].level
	})

	out, err := os.Create(*output)
	if err != nil {
		fatal("create %s: %v", *output, err)
	}
	defer out.Close()
	fmt.Fprintln(out, "// Code generated by tools/generate_skill_recovery; DO NOT EDIT.")
	fmt.Fprintf(out, "// Skill.SData SHA-256: %s\n", hex.EncodeToString(skillHash[:]))
	fmt.Fprintf(out, "// Action/ANI content SHA-256: %x\n", assetHash.Sum(nil))
	fmt.Fprintln(out, "package world\n")
	fmt.Fprintln(out, "type skillRecoveryKey struct { id uint16; level uint8 }")
	fmt.Fprintln(out, "var skillRecoveryMillis = map[skillRecoveryKey]uint32{")
	for _, key := range keys {
		fmt.Fprintf(out, "\t{id: %d, level: %d}: %d,\n", key.id, key.level, durations[key])
	}
	fmt.Fprintln(out, "}")
	if err := out.Close(); err != nil {
		fatal("close %s: %v", *output, err)
	}
	appOut, err := os.Create(*appOutput)
	if err != nil {
		fatal("create %s: %v", *appOutput, err)
	}
	fmt.Fprintln(appOut, "// Code generated by tools/generate_skill_recovery; DO NOT EDIT.")
	fmt.Fprintf(appOut, "// Skill.SData SHA-256: %s\n", hex.EncodeToString(skillHash[:]))
	fmt.Fprintf(appOut, "// Action/ANI content SHA-256: %x\n", assetHash.Sum(nil))
	fmt.Fprintln(appOut, "package app\n")
	fmt.Fprintln(appOut, "type clientSkillRecoveryKey struct { id uint16; level uint8 }")
	fmt.Fprintln(appOut, "var clientSkillRecoveryMillis = map[clientSkillRecoveryKey]uint32{")
	for _, key := range keys {
		fmt.Fprintf(appOut, "\t{id: %d, level: %d}: %d,\n", key.id, key.level, durations[key])
	}
	fmt.Fprintln(appOut, "}")
	fmt.Fprintln(appOut, "func skillRecoverySeconds(id uint16, level uint8) float64 {")
	fmt.Fprintln(appOut, "\treturn float64(clientSkillRecoveryMillis[clientSkillRecoveryKey{id: id, level: level}]) / 1000")
	fmt.Fprintln(appOut, "}")
	if err := appOut.Close(); err != nil {
		fatal("close %s: %v", *appOutput, err)
	}
	fmt.Printf("skills=%d mapped=%d action_alts=%d clips=%d skill_sdata_sha256=%x action_sha256=%x\n",
		len(skills), len(durations), len(actionFiles), len(clips), skillHash, assetHash.Sum(nil))
}

func fatal(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}

// Keep this table aligned with internal/scene/actions.go. Duplicating these
// small selectors avoids linking the rendering stack into this offline tool.
func skillAction(animation uint16, attack, effect, weapon, variant uint8) int {
	if (effect == 1 || effect == 3 || effect == 5) && attack != 0 {
		if attack == 1 || attack == 2 {
			if a := int(uint8(animation)); a >= 100 && a <= 110 {
				return a
			}
			return attackAction(weapon, variant)
		}
		if uint8(animation) == 1 {
			return 90
		}
		return 87
	}
	return 93
}

func attackAction(weapon, variant uint8) int {
	v := int(variant % 4)
	switch weapon {
	case 1, 3, 7:
		return 35 + v
	case 2, 4, 8:
		return 24 + v
	case 5:
		return 42 + v
	case 6:
		return 49 + v
	case 9:
		return 65 + v
	case 10:
		return 79 + v
	case 11, 14:
		return 56
	case 12:
		return 60 + int(variant%2)
	case 13:
		return 31
	case 15:
		return 72 + v
	default:
		return 1
	}
}
